param([string]$XamppRoot='C:\xampp',[string]$AppPath='C:\xampp\htdocs\VPR_EXCEL',[string]$PublicUrl='https://localhost/VPR_EXCEL')
$ErrorActionPreference='Stop'
if($PublicUrl -notmatch '^https://localhost(?:/[A-Za-z0-9_-]+)+/?$'){throw 'Use the local HTTPS VPR application URL.'}
$configPath=Join-Path $XamppRoot 'apache\conf\extra\vpr-paynow-local.conf'
$mainPath=Join-Path $XamppRoot 'apache\conf\httpd.conf'
$lines=@('# Generated by VPR local test setup. Contains secrets; do not commit.',('<Directory "'+$AppPath.Replace('\','/')+'">'))
foreach($currency in @('USD','ZWG')){
 foreach($suffix in @('ID','KEY','ENVIRONMENT','ENABLED','CURRENCY_CONFIRMED')){
  $name='VPR_PAYNOW_'+$currency+'_'+$suffix
  $value=[Environment]::GetEnvironmentVariable($name,'User')
  if(-not $value -or $value -notmatch '^[A-Za-z0-9_-]+$'){throw "Missing or invalid user environment variable: $name"}
  if($suffix -eq 'ENVIRONMENT' -and $value -ne 'test'){throw 'This local setup requires test credentials.'}
  $lines+=('    SetEnv '+$name+' "'+$value+'"')
 }
}
$lines+=('    SetEnv VPR_PUBLIC_URL "'+$PublicUrl.TrimEnd('/')+'"')
$lines+='</Directory>'
$main=[IO.File]::ReadAllText($mainPath)
if(Test-Path -LiteralPath $configPath){
 $old=[IO.File]::ReadAllText($configPath)
 if(-not $old.StartsWith('# Generated by VPR local test setup.')){throw 'Existing local configuration is not owned by this setup tool.'}
}
[IO.File]::WriteAllLines($configPath,$lines)
$include='Include conf/extra/vpr-paynow-local.conf'
if(-not $main.Contains($include)){
 Copy-Item -LiteralPath $mainPath -Destination ($mainPath+'.before-vpr-'+(Get-Date -Format 'yyyyMMddHHmmss')+'.bak')
 [IO.File]::WriteAllText($mainPath,$main+"`r`n"+$include+"`r`n")
}
& (Join-Path $XamppRoot 'apache\bin\httpd.exe') -t
if($LASTEXITCODE -ne 0){[IO.File]::WriteAllText($mainPath,$main);throw 'Apache syntax check failed; main configuration restored.'}
Write-Output 'Apache test profiles configured outside the document root. Restart Apache to load them. Keys were not printed or stored in Git.'
